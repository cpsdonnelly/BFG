"""Convoy, the narrative scenario (XR p.94-95): the convoy runs from one
short edge to the other through hidden contact markers hiding the attacker's
ships, deadfall torpedoes and attack craft clusters.

The attacker's force is generated by the scenario's D6 table (two rolls plus
one per 2 transport capacity); its built fleet is replaced (reading: "the
attacker generates his or her forces randomly"), keeping its faction. The
ships it generates wait off the table (reserve) until their contact marker is
activated.
"""
from __future__ import annotations

import math
from typing import Dict, List, Optional, Tuple

MARKER_GAP = 30.0          # markers 30cm apart and 30cm from every edge
ACTIVATE_RANGE = 30.0      # a defending vessel within 30cm activates a marker
ENTRY_LONG_GAP = 45.0      # the entry point at least 45cm from either long edge
DEADFALL_SPEED = 30.0


def active(gs) -> bool:
    return getattr(gs, "scenario_mode", "") == "convoy_narrative"


def _key(s) -> str:
    return s.squadron_id if (s.ship_type == "escort" and s.squadron_id) else s.id


# --- the attacker's random force -----------------------------------------------------

def _pick_capital(faction: str, limit: int):
    from .ship_catalog import get_faction_ships
    caps = [e for e in get_faction_ships(faction)
            if e.ship_type not in ("escort", "defense") and e.points_cost
            and e.points_cost <= limit and e.speed > 0 and _warship(e)]
    return max(caps, key=lambda e: (e.points_cost, e.ship_class), default=None)


def _warship(e) -> bool:
    rules = e.special_rules or []
    return not any(r == "immobile" or r == "unique" or r.startswith("transport")
                   for r in rules) and bool(e.weapons)


def _pick_escorts(faction: str, limit: int):
    """The escort class and count for a squadron worth up to `limit`
    (judgement: the class giving the most points within it, ties to more
    ships)."""
    from .ship_catalog import get_faction_ships
    best = None
    for e in get_faction_ships(faction):
        if e.ship_type != "escort" or not e.points_cost or e.points_cost > limit \
                or e.speed <= 0 or not _warship(e):
            continue
        n = min(6, limit // e.points_cost)
        cand = (n * e.points_cost, n, e.ship_class, e)
        if best is None or cand[:2] > best[:2]:
            best = cand
    return (best[3], best[1]) if best else (None, 0)


def generate_force(gs, dice, faction: str, capacity: float) -> List[Dict]:
    """Roll the attacker's force: 2 + one per 2 transport capacity rolls.
    1-3: that many deadfall torpedo / attack craft clusters (judgement:
    alternately torpedoes then craft); 4 / 5: an escort squadron up to 100 /
    150pts; 6: a capital ship up to 200pts. Returns the units as
    {"kind": "torpedoes" | "craft" | "unit", "ships": [ids]}; ships are added
    to the game in reserve."""
    from .models import Ship
    from .scenarios import _to_reserve
    att = gs.scenario_attacker
    rolls = 2 + int(capacity // 2)
    units: List[Dict] = []
    clusters = 0
    n_ship = 0
    for i in range(rolls):
        r = dice.roll_d6(1, f"Convoy: attacker's force roll {i + 1} of {rolls}")[0]
        if r <= 3:
            for _ in range(r):
                units.append({"kind": "torpedoes" if clusters % 2 == 0 else "craft"})
                clusters += 1
            continue
        if r == 6:
            e = _pick_capital(faction, 200)
            picks = [(e, 1)] if e else []
        else:
            e, n = _pick_escorts(faction, 100 if r == 4 else 150)
            picks = [(e, n)] if e and n else []
        if not picks:
            gs.add_log(f"[Convoy] roll {r}: no {faction} ship fits; nothing taken")
            continue
        e, n = picks[0]
        ids = []
        sq = f"convoy_att_sq{n_ship}" if e.ship_type == "escort" else ""
        for k in range(n):
            sid = f"convoy_att_{n_ship}_{k}"
            d = e.to_ship_dict(e.ship_class, att, ship_id=sid)
            d.update(x=0.0, y=0.0, heading=0.0, squadron_id=sq)
            gs.add_ship(Ship.from_dict(d))
            _to_reserve(next(sd for sd in gs.ships if sd["id"] == sid))
            ids.append(sid)
        n_ship += 1
        units.append({"kind": "unit", "ships": ids, "name": f"{n} x {e.ship_class}"})
    return units


def defender_capacity(gs) -> float:
    from .scenarios import transport, defender
    return sum(transport(s, building=True) for s in gs.get_ships() if s.player == defender(gs))


def marker_spots(gs, n: int) -> List[Tuple[float, float]]:
    """Contact marker positions (judgement): a grid 30cm apart, at least 30cm
    from every edge, filled from the middle of the table outwards; when they
    don't all fit they double up, as the rules say."""
    w, h = gs.table_width, gs.table_height
    xs = [MARKER_GAP + MARKER_GAP * i for i in range(int((w - 2 * MARKER_GAP) // MARKER_GAP) + 1)]
    ys = [MARKER_GAP + MARKER_GAP * i for i in range(int((h - 2 * MARKER_GAP) // MARKER_GAP) + 1)]
    grid = sorted(((x, y) for x in xs for y in ys),
                  key=lambda p: (math.hypot(p[0] - w / 2.0, p[1] - h / 2.0), p))
    if not grid:
        grid = [(w / 2.0, h / 2.0)]
    return [grid[i % len(grid)] for i in range(n)]


def setup(gs, dice) -> None:
    """The attacker's force generated and its contact markers placed; the
    defender's entry point (a D6 for the short edge: 1-3 left, 4-6 right,
    reading; centred between the long edges, which keeps it 45cm from both);
    the defender's ships wait off the table and move on from it in its first
    turn."""
    from .scenarios import _to_reserve, defender, _main_faction
    att, dfn = gs.scenario_attacker, defender(gs)
    faction = _main_faction(gs, att) or "imperial_navy_gothic"
    built = [sd["id"] for sd in gs.ships if sd["player"] == att]
    gs.ships = [sd for sd in gs.ships if sd["player"] != att]
    cap = defender_capacity(gs)
    units = generate_force(gs, dice, faction, cap)
    spots = marker_spots(gs, len(units))
    markers = []
    for i, (u, (x, y)) in enumerate(zip(units, spots)):
        markers.append(dict(u, id=f"contact_{i}", x=x, y=y, active=False))
    edge = "left" if dice.roll_d6(1, "Convoy: the convoy's entry edge (1-3 left, "
                                     "4-6 right)")[0] <= 3 else "right"
    for sd in gs.ships:
        if sd["player"] == dfn:
            _to_reserve(sd)
    gs.scenario_state = {"markers": markers, "entry_edge": edge,
                         "entry_y": gs.table_height / 2.0, "faction": faction,
                         "replaced": built, "escaped": [], "start_pos": {}}
    kinds = {k: sum(1 for u in units if u["kind"] == k) for k in ("unit", "torpedoes", "craft")}
    gs.add_log(f"[Convoy] the attacker's force: {kinds['unit']} ship unit(s), "
               f"{kinds['torpedoes']} deadfall torpedo and {kinds['craft']} attack craft "
               f"cluster(s) behind {len(markers)} contact markers; the convoy enters from the "
               f"{edge} edge")


def exit_edge_for(gs) -> str:
    return "right" if (gs.scenario_state or {}).get("entry_edge") == "left" else "left"


def force_errors(gs) -> List[str]:
    """The defender's limit: half its transport capacity (rounded down) x 100
    pts of other ships; at least 2 capacity; convoy squadrons of 2+ ships or
    2+ capacity (warnings)."""
    from .scenarios import transport, defender, is_convoy
    errs = []
    dfn = defender(gs)
    cap = defender_capacity(gs)
    if cap < 2:
        errs.append("Convoy: the defender needs at least 2 transport capacity")
    pts = sum(s.points_value for s in gs.get_ships() if s.player == dfn and not is_convoy(s))
    if pts > int(cap // 2) * 100:
        errs.append(f"Convoy: the escorting fleet may cost {int(cap // 2) * 100} pts "
                    f"(half the capacity x 100), has {pts}")
    groups: Dict[str, List] = {}
    for s in gs.get_ships():
        if s.player == dfn and is_convoy(s):
            groups.setdefault(_key(s), []).append(s)
    for k, ss in groups.items():
        if len(ss) < 2 and sum(transport(s, building=True) for s in ss) < 2:
            errs.append(f"Convoy: {ss[0].name} must be in a squadron of 2+ ships or 2+ capacity")
    return errs


# --- play --------------------------------------------------------------------------------

def arrival_y(gs) -> float:
    return (gs.scenario_state or {}).get("entry_y", gs.table_height / 2.0)


def wants_arrival(gs, player: int, key: str, hook_answer: bool) -> bool:
    """The defender may hold back up to half its ships (by count, reading)
    for its second turn; from the second turn on everything comes on."""
    from .scenarios import reserve_units
    game_turn = gs.turn_number if getattr(gs, "turn_system", "igougo") == "aa" \
        else (gs.turn_number + 1) // 2
    if game_turn >= 2 or hook_answer:
        return True
    st = gs.scenario_state or {}
    held = st.get("held", [])
    total = sum(1 for s in gs.get_ships() if s.player == player)
    waiting = sum(len(v) for k, v in reserve_units(gs, player).items() if k in held)
    size = len(reserve_units(gs, player).get(key, []))
    if 2 * (waiting + size) > total:
        return True
    st = dict(st)
    st["held"] = sorted(set(held) | {key})
    gs.scenario_state = st
    return False


def record_start_positions(gs, player: int) -> None:
    """The defender's ships' positions at the start of its movement phase
    (the marker check follows each ship's straight line from there)."""
    st = dict(gs.scenario_state or {})
    st["start_pos"] = {s.id: [s.x, s.y] for s in gs.get_ships() if s.player == player
                       and not s.is_destroyed and not s.is_disengaged}
    gs.scenario_state = st


def _seg_dist(px, py, ax, ay, bx, by) -> float:
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / max(1e-9, dx * dx + dy * dy)))
    return math.hypot(px - ax - t * dx, py - ay - t * dy)


def check_activation(gs) -> List[str]:
    """A marker is activated once a defending vessel moves within 30cm of it
    (reading: on the straight line from where the ship started its movement
    phase to where it ended, or its arrival point)."""
    from .scenarios import defender
    st = dict(gs.scenario_state or {})
    starts = st.get("start_pos", {})
    out = []
    markers = [dict(m) for m in st.get("markers", [])]
    for m in markers:
        if m["active"] or m.get("deployed"):
            continue
        for s in gs.get_ships():
            if s.player != defender(gs) or s.is_destroyed or s.is_disengaged:
                continue
            a = starts.get(s.id, [s.x, s.y])
            if _seg_dist(m["x"], m["y"], a[0], a[1], s.x, s.y) <= ACTIVATE_RANGE:
                m["active"] = True
                out.append(m["id"])
                break
    st["markers"] = markers
    gs.scenario_state = st
    return out


def deploy_marker(gs, marker: Dict, dice) -> None:
    """Replace an activated marker by what it hides, facing the nearest
    defending ship (judgement for the attacker's choices)."""
    from .models import OrdnanceMarker, OrdnanceType
    from .scenarios import defender
    targets = [s for s in gs.get_ships() if s.player == defender(gs)
               and not s.is_destroyed and not s.is_disengaged]
    near = min(targets, key=lambda s: math.hypot(s.x - marker["x"], s.y - marker["y"]),
               default=None)
    hd = math.degrees(math.atan2(near.y - marker["y"], near.x - marker["x"])) % 360.0 \
        if near else 0.0
    att = gs.scenario_attacker
    if marker["kind"] == "torpedoes":
        n = dice.roll_d6(1, "Deadfall torpedoes: strength (D6+2)")[0] + 2
        gs.add_ordnance(OrdnanceMarker(
            id=f"deadfall_{marker['id']}", ordnance_type=OrdnanceType.TORPEDO_STANDARD.value,
            owner_player=att, launched_by="", x=marker["x"], y=marker["y"], heading=hd,
            strength=n, speed=DEADFALL_SPEED, launched_turn=gs.turn_number))
        gs.add_log(f"[Convoy] {marker['id']}: deadfall torpedoes, strength {n}")
    elif marker["kind"] == "craft":
        n = (dice.roll_d6(1, "Attack craft cluster: squadrons (D3+1)")[0] + 1) // 2 + 1
        wave = f"cluster_{marker['id']}"
        kinds = [OrdnanceType.FIGHTER.value] * (n // 2) + [OrdnanceType.BOMBER.value] * (n - n // 2)
        for i, k in enumerate(kinds):
            gs.add_ordnance(OrdnanceMarker(
                id=f"{wave}_{i}", ordnance_type=k, owner_player=att, launched_by="",
                x=marker["x"], y=marker["y"], heading=hd,
                speed=30.0 if k == OrdnanceType.FIGHTER.value else 20.0,
                launched_turn=gs.turn_number, wave_id=wave, wave_order=i,
                wave_formation="close",
                craft_target_id=near.id if near else ""))
        gs.add_log(f"[Convoy] {marker['id']}: an attack craft cluster, {n} squadron(s) "
                   f"(fighters lead, bombers behind, one wave)")
    else:
        ships = [gs.get_ship_by_id(sid) for sid in marker.get("ships", [])]
        ships = [s for s in ships if s is not None]
        for i, s in enumerate(ships):
            # the first on the marker, the rest in formation behind it
            back = 4.0 * i
            s.x = max(3.0, min(gs.table_width - 3.0,
                               marker["x"] - back * math.cos(math.radians(hd))))
            s.y = max(3.0, min(gs.table_height - 3.0,
                               marker["y"] - back * math.sin(math.radians(hd))))
            s.heading = hd
            s.status = "active"
            s.is_disengaged = False
            gs.update_ship(s)
        gs.add_log(f"[Convoy] {marker['id']}: {marker.get('name', 'ships')} revealed")
    st = dict(gs.scenario_state or {})
    st["markers"] = [dict(m, deployed=True, active=True) if m["id"] == marker["id"] else m
                     for m in st.get("markers", [])]
    gs.scenario_state = st


def end_of_defender_movement(gs, player: int, dice) -> None:
    """After the defender's movement phase: activate markers its ships came
    within 30cm of and deploy their forces."""
    from .scenarios import defender, _dice_for
    if not active(gs) or player != defender(gs):
        return
    check_activation(gs)
    roll = _dice_for(gs, gs.scenario_attacker, dice) or _auto()
    for m in list((gs.scenario_state or {}).get("markers", [])):
        if m["active"] and not m.get("deployed"):
            deploy_marker(gs, m, roll)


def _auto():
    from .dice import DiceRoller
    return DiceRoller(mode="auto")


def attacker_turn_start(gs, player: int, dice) -> None:
    """At the start of the attacker's movement phase it may activate one
    marker, two if any defending ship is on special orders (judgement: always,
    the hidden markers nearest the convoy first)."""
    from .scenarios import defender, is_convoy, _dice_for
    if not active(gs) or player != gs.scenario_attacker:
        return
    st = gs.scenario_state or {}
    hidden = [m for m in st.get("markers", []) if not m["active"]]
    if not hidden:
        return
    dfn = [s for s in gs.get_ships() if s.player == defender(gs)
           and not s.is_destroyed and not s.is_disengaged]
    if not dfn:
        return
    n = 1 + (1 if any(s.special_order not in ("", "none", None) for s in dfn) else 0)
    goals = [s for s in dfn if is_convoy(s)] or dfn
    hidden.sort(key=lambda m: min(math.hypot(m["x"] - s.x, m["y"] - s.y) for s in goals))
    roll = _dice_for(gs, player, dice) or _auto()
    for m in hidden[:n]:
        gs.add_log(f"[Convoy] the attacker activates {m['id']}")
        deploy_marker(gs, m, roll)


def record_exit(gs, ship) -> None:
    from .scenarios import exit_edge, is_convoy, defender
    if active(gs) and ship.player == defender(gs) and is_convoy(ship) \
            and exit_edge(gs, ship) == exit_edge_for(gs):
        st = dict(gs.scenario_state or {})
        st["escaped"] = sorted(set(st.get("escaped", [])) | {ship.id})
        gs.scenario_state = st


def capacity_escaped(gs) -> int:
    """Transport capacity of the convoy ships off the far short edge (their
    current capacity, rounded down)."""
    from .scenarios import transport
    esc = set((gs.scenario_state or {}).get("escaped", []))
    return int(sum(transport(s) for s in gs.get_ships() if s.id in esc))


RESULTS = {0: "Attackers Win", 1: "Attackers Marginal Win", 2: "Convoy Marginal Win"}


def result_text(gs) -> str:
    n = capacity_escaped(gs)
    return RESULTS.get(n, "Convoy Win") + f" ({n} transport capacity escaped)"


def attacker_spent(gs) -> bool:
    """No attacking ships, hidden markers, deadfall torpedoes or attack craft
    left."""
    att = gs.scenario_attacker
    st = gs.scenario_state or {}
    if any(not m.get("deployed") for m in st.get("markers", [])):
        return False
    if any(s.player == att and not s.is_destroyed and not s.is_disengaged
           for s in gs.get_ships()):
        return False
    return not any(o.owner_player == att for o in gs.get_ordnance())


def convoy_left(gs) -> bool:
    """Convoy ships still on the board or still to come on."""
    from .scenarios import is_convoy, defender
    return any(s.player == defender(gs) and is_convoy(s) and not s.is_destroyed
               and (not s.is_disengaged or s.status == "reserve") for s in gs.get_ships())


def winner(gs) -> int:
    from .scenarios import defender
    if attacker_spent(gs) and (capacity_escaped(gs) >= 1 or convoy_left(gs)):
        return defender(gs)
    return defender(gs) if capacity_escaped(gs) >= 2 else gs.scenario_attacker


def check_end(gs) -> Optional[dict]:
    if not active(gs) or gs.turn_number < 2:
        return None
    if not convoy_left(gs):
        return {"winner": winner(gs), "reason": "convoy_gone", "detail": result_text(gs)}
    if attacker_spent(gs):
        from .scenarios import defender
        return {"winner": defender(gs), "reason": "attacker_gone",
                "detail": "the attacking fleet is gone: the convoy wins"}
    return None


# --- AI -------------------------------------------------------------------------------

CAPACITY_WEIGHT = 0.1     # judgement: three capacity out decide the game


def capacity_vp(gs) -> float:
    from .scenarios import table_points
    return CAPACITY_WEIGHT * max(300.0, table_points(gs))


def exit_value(gs, ship) -> float:
    from .scenarios import transport, defender, is_convoy
    if not active(gs) or ship.player != defender(gs) or not is_convoy(ship):
        return 0.0
    return transport(ship) * capacity_vp(gs) + ship.points_value
